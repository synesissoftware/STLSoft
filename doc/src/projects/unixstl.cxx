/** \defgroup group__project__unixstl UNIXSTL
 * \ingroup group__projects
 *
 * \brief &nbsp;&nbsp;&nbsp;&nbsp;Template Software for the UNIX Operating System.
 *
 * <img src="unixstl32x32.jpg" width="32" height="32" align="left" />
 *
 * The philosophy of UNIXSTL (http://unixstl.org/) is essentially the same as that
 * of the STLSoft (http://stlsoft.org/) organisation: providing robust and
 * lightweight software to the Active Template Library (ATL) development
 * community. UNIXSTL provides template-based software that builds on that
 * provided by ATL and STLSoft in order to reduce programmer effort and increase
 * robustness in the use of the ATL.
 *
 * All components in the <b>UNIXSTL</b> project reside in the ::unixstl namespace
 *
 * As with <b><i>all</i></b> parts of the STLSoft libraries, there are no
 * dependencies on UNIXSTL binary components and no need to compile UNIXSTL
 * implementation files; UNIXSTL is <b>100%</b> header-only!
 *
 * The only other dependencies are on UNIX headers and binary components.
 */

