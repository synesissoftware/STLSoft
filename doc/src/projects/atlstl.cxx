/** \defgroup group__project__atlstl ATLSTL
 * \ingroup group__projects
 *
 * \brief &nbsp;&nbsp;&nbsp;&nbsp;Template Software for the Active Template Library (ATL).
 *
 * <img src="atlstl32x32.jpg" width="32" height="32" align="left" />
 *
 * The <b>ATLSTL</b> sub-project provides template-based software that
 * builds on that provided by ATL and STLSoft in order to reduce programmer
 * effort and increase robustness in the use of the ATL.
 *
 * All components in the <b>ATLSTL</b> project reside in the ::atlstl namespace
 *
 * As with <b><i>all</i></b> parts of the STLSoft libraries, there are no
 * dependencies on ATLSTL binary components and no need to compile ATLSTL
 * implementation files; ATLSTL is <b>100%</b> header-only!
 *
 * The only other dependencies are on the ATL headers and binary components.
 */

