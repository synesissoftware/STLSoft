/** \defgroup group__library__Container Container Library
 * \ingroup group__libraries
 *
 * \brief This library defines containers that extend the STL.
 *
 * The STL-containers provided by the STLSoft libraries include:
 *
 * - The stlsoft::basic_environment_block - stores nul-terminated environment
 *    variable name-value strings continguously in a format compatible with
 *    system environment settings.
 * - The "fixed array" multidimensional array class templates
 *    (\link stlsoft::fixed_array_1d fixed_array_1d\endlink,
 *     \link stlsoft::fixed_array_2d fixed_array_2d\endlink,
 *     \link stlsoft::fixed_array_3d fixed_array_3d\endlink,
 *     \link stlsoft::fixed_array_4d fixed_array_4d\endlink) - <b>genuine
 *    dynamically-sized multi-dimensional arrays for C++</b>.
 * - The stlsoft::frequency_map - provides frequency recording of inserted
 *    elements
 * - The stlsoft::pod_vector - a vector of POD types that uses
 *    stlsoft::auto_buffer to optimise storage
 * - The "static array" multidimensional array class templates
 *    (\link stlsoft::static_array_1d static_array_1d\endlink,
 *     \link stlsoft::static_array_2d static_array_2d\endlink,
 *     \link stlsoft::static_array_3d static_array_3d\endlink,
 *     \link stlsoft::static_array_4d static_array_4d\endlink) - statically
 *    sized multi-dimensional arrays for C++.
 * - The stlsoft::unsorted_map - associative container that maintains the
 *    insertion order of its elements.
 *
 */
